#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
tools/generate-data.py

Reverse glyph data exporter for the custom SVG glyph format.

Reads:
  src/character-u{codepoint}.svg
  src/ligature-uXXXX-uYYYY(-uZZZZ...).svg

Writes:
  data/glyphs.json
  data/glyphs.py

What it extracts per glyph:
- character / codepoint metadata
- width / height (from SVG viewBox)
- raw polygon points
- rectangle form (x1,y1,x2,y2) when polygons are axis-aligned rectangles
- grid occupancy based on the known MMXX-style partition grid
  - singles use the standard X_BREAKS up to 20
  - ligatures use extended xBreaks in steps of 4 up to glyph width
- active cell coordinates

Ligatures:
- Stored separately in DATA["ligatures"].
- Keyed by sequence string like "u0073-u0074".
- Record also includes "key" (the actual character string, e.g. "st"),
  "sequence" (list of codepoints), and "sequenceKey" (string id).

This is designed to work with glyphs generated by your current SVG generator
(and also with manually edited/exported glyphs from the glyph designer).
"""

from __future__ import annotations

import argparse
import json
import math
import re
import sys
import unicodedata
import xml.etree.ElementTree as ET
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from pprint import pformat
from typing import Any, Dict, List, Sequence, Tuple, Optional

# -----------------------------
# Known grid (from your typeface system)
# -----------------------------
# NOTE: Singles historically fit within 0..20; ligatures can be wider.
# We'll keep these as the canonical "single-glyph" breaks.
X_BREAKS = [0, 4, 8, 12, 16, 20]
Y_BREAKS = [0, 1, 4, 9, 10, 14, 15, 19, 20, 25, 29, 30]
CELL_H = 30
GRID_STEP_X = 4

# Small tolerance for float parsing / comparisons (in case edited SVGs contain "12.0")
EPS = 1e-9

CHAR_SVG_RE = re.compile(r"^character-u([0-9a-fA-F]+)\.svg$")
LIGA_SVG_RE = re.compile(
    r"^ligature-((?:u[0-9a-fA-F]+)(?:-u[0-9a-fA-F]+)+)\.svg$"
)

Point = Tuple[float, float]
Poly = List[Point]
Rect = Tuple[float, float, float, float]


@dataclass
class ParsedGlyph:
    kind: str                 # "char" or "liga"
    key: str                  # char kind: "u0061" ; liga kind: "u0073-u0074"
    char: str                 # char kind: "a" ; liga kind: "st" (may be multi-char)
    codepoint: Optional[int]  # char kind: 97 ; liga kind: None
    sequence: Optional[List[int]]  # char kind: None ; liga kind: [0x73,0x74]
    filename: str             # e.g. "character-u0061.svg" or "ligature-u0073-u0074.svg"
    width: float
    height: float
    polys: List[Poly]
    rects: List[Rect]
    warnings: List[str]


